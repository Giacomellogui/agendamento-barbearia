import { conexao, usaPostgres } from "./conexao.ts";

export const banco = conexao;
const id = usaPostgres ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY";
const idServico = usaPostgres ? "INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY" : id;

async function colunas(tabela: "clientes" | "reservas" | "avisos_whatsapp") {
  const linhas = usaPostgres
    ? await banco.prepare("SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ?").all(tabela)
    : await banco.prepare(`PRAGMA table_info(${tabela})`).all();
  return linhas.map(({ name }) => name);
}

// Inicializa ou migra o banco antes de abrir a porta HTTP.
try {
  await banco.transacao(inicializar);
} catch (erro) {
  const codigo = erro && typeof erro === "object" && "code" in erro && typeof erro.code === "string"
    && /^[A-Z0-9_]+$/.test(erro.code) ? ` Código: ${erro.code}.` : "";
  console.error("Não foi possível inicializar o banco. Confira a conexão e as permissões do banco configurado." + codigo);
  process.exit(1);
}

async function inicializar() {
  await banco.exec(`
    CREATE TABLE IF NOT EXISTS reservas (
      id ${id},
      nome TEXT NOT NULL,
      servico_id INTEGER NOT NULL,
      data TEXT NOT NULL,
      inicio INTEGER NOT NULL,
      fim INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS servicos (
      id ${idServico},
      nome TEXT NOT NULL,
      "duracaoMinutos" INTEGER NOT NULL,
      "precoCentavos" INTEGER
    );
    CREATE TABLE IF NOT EXISTS expediente (
      id INTEGER PRIMARY KEY CHECK (id = 1),
      dias INTEGER NOT NULL,
      abertura TEXT NOT NULL,
      fechamento TEXT NOT NULL,
      "inicioPausa" TEXT,
      "fimPausa" TEXT
    );
    CREATE TABLE IF NOT EXISTS clientes (
      id ${id},
      nome TEXT NOT NULL,
      telefone TEXT NOT NULL UNIQUE,
      salt TEXT NOT NULL,
      hash TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS links_cliente (
      cliente_id INTEGER NOT NULL REFERENCES clientes(id),
      tipo TEXT NOT NULL CHECK (tipo IN ('verificacao', 'recuperacao')),
      email TEXT NOT NULL,
      digest TEXT UNIQUE,
      expira_em BIGINT NOT NULL,
      solicitado_em BIGINT NOT NULL,
      janela_inicio BIGINT NOT NULL,
      envios INTEGER NOT NULL,
      PRIMARY KEY (cliente_id, tipo)
    );
    CREATE TABLE IF NOT EXISTS avisos_whatsapp (
      id ${id},
      reserva_id INTEGER NOT NULL,
      anterior TEXT NOT NULL,
      novo TEXT NOT NULL,
      proxima_tentativa BIGINT NOT NULL,
      tentativas INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS bloqueios (
      id ${id},
      data TEXT NOT NULL,
      inicio INTEGER NOT NULL,
      fim INTEGER NOT NULL,
      CHECK (inicio >= 0 AND fim <= 1440 AND inicio < fim)
    );
    CREATE INDEX IF NOT EXISTS bloqueios_data ON bloqueios (data);
    INSERT INTO expediente VALUES (1, 127, '09:00', '18:00', NULL, NULL) ON CONFLICT (id) DO NOTHING;
    INSERT INTO servicos VALUES
      (1, 'Corte de cabelo', 30, NULL),
      (2, 'Barba', 20, NULL),
      (3, 'Corte e barba', 50, NULL) ON CONFLICT (id) DO NOTHING;
  `);

  // As contas que já existem podem adicionar um e-mail após entrar pelo telefone.
  if (!(await colunas("clientes")).includes("email_verificado")) {
    await banco.exec("ALTER TABLE clientes ADD COLUMN email_verificado TEXT");
  }
  await banco.exec("CREATE UNIQUE INDEX IF NOT EXISTS clientes_email_verificado ON clientes (email_verificado) WHERE email_verificado IS NOT NULL");

  // Acrescenta os campos de histórico sem recriar a tabela de reservas.
  const colunasReserva = await colunas("reservas");
  if (!colunasReserva.includes("cliente_id")) {
    await banco.exec("ALTER TABLE reservas ADD COLUMN cliente_id INTEGER REFERENCES clientes(id)");
  }
  if (!colunasReserva.includes("cancelada_em")) {
    await banco.exec("ALTER TABLE reservas ADD COLUMN cancelada_em TEXT");
  }
  if (!colunasReserva.includes("servico_nome")) {
    await banco.exec("ALTER TABLE reservas ADD COLUMN servico_nome TEXT");
    await banco.exec("UPDATE reservas SET servico_nome = (SELECT nome FROM servicos WHERE id = reservas.servico_id)");
  }
  if (!colunasReserva.includes("comparecimento")) {
    await banco.exec(`ALTER TABLE reservas ADD COLUMN comparecimento TEXT
      CHECK (comparecimento IN ('concluido', 'falta'))`);
  }
  await banco.exec("CREATE INDEX IF NOT EXISTS reservas_cliente_data ON reservas (cliente_id, data DESC, inicio DESC)");

  // Os avisos antigos ainda na fila começam como pendentes.
  const colunasAviso = await colunas("avisos_whatsapp");
  if (!colunasAviso.includes("estado")) {
    await banco.exec("ALTER TABLE avisos_whatsapp ADD COLUMN estado TEXT NOT NULL DEFAULT 'pendente'");
  }
  if (!colunasAviso.includes("erro")) {
    await banco.exec("ALTER TABLE avisos_whatsapp ADD COLUMN erro TEXT");
  }
}
